"""The tide cell key's rounding is pinned to the fixture the client tests against (#791 follow-up).

frontend/src/components/map/tideRoundOracle.fixture.json holds Python round(x, 1) for ~10k hard
inputs (exact .25/.75 ties and their binary neighbours, x.x5 decimals, signed zero, +/-90 and
+/-180, a seeded sweep), generated by frontend/scripts/gen_tide_round_oracle.py. The client's
tideCellKey is asserted against it in tideRoundOracle.test.js. This test pins the backend side:
if tide._round_key stops being round(x, 1), the two sides would fetch different ~0.1 degree cells,
and this goes red instead of the client test silently testing against a stale oracle.
"""
import json
import math
from pathlib import Path

import pytest

from services.weather_pipeline.tide import _round_key

FIXTURE = (
    Path(__file__).resolve().parents[2] / "frontend" / "src" / "components" / "map" / "tideRoundOracle.fixture.json"
)


@pytest.fixture(scope="module")
def oracle():
    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    assert len(doc["inputs"]) == len(doc["expected"]) == doc["count"] > 9000
    return doc


def test_round_key_equals_the_fixture_for_every_input(oracle):
    xs, want = oracle["inputs"], oracle["expected"]
    n = len(xs)
    bad = []
    for i, x in enumerate(xs):
        y = xs[n - 1 - i]
        got = _round_key(x, y)
        if got != (want[i], want[n - 1 - i]):
            bad.append((x, y, got, want[i], want[n - 1 - i]))
            if len(bad) >= 20:
                break
    assert bad == []


def test_round_key_keeps_the_sign_of_zero_and_ties_to_even(oracle):
    xs = oracle["inputs"]
    assert any(x == 0.0 and math.copysign(1.0, x) < 0 for x in xs)  # -0.0 survived the JSON
    assert math.copysign(1.0, _round_key(-0.0, 0)[0]) < 0
    assert _round_key(0.25, -0.25) == (0.2, -0.2)
    assert _round_key(0.75, -179.75) == (0.8, -179.8)
    assert _round_key(math.nextafter(0.25, 1.0), 0.15) == (0.3, 0.1)


def test_fixture_matches_its_generator():
    """The committed fixture is exactly what the generator script produces now."""
    import importlib.util

    gen_path = Path(__file__).resolve().parents[2] / "frontend" / "scripts" / "gen_tide_round_oracle.py"
    spec = importlib.util.spec_from_file_location("gen_tide_round_oracle", gen_path)
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    xs = gen.inputs()
    assert [repr(x) for x in doc["inputs"]] == [repr(x) for x in xs]
    assert doc["expected"] == [round(x, 1) for x in xs]
