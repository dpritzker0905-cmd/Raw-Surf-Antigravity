import { createRequire } from 'module';
const require = createRequire(new URL('../../package.json', import.meta.url));
const { chromium } = require('playwright');
const url = new URL('./out/ground-truth.local.html', import.meta.url).href;
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader-webgl', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: Number(process.env.VW || 1500), height: Number(process.env.VH || 1000) } });
const logs = [];
page.on('console', (m) => logs.push(m.type() + ': ' + m.text()));
page.on('pageerror', (e) => logs.push('pageerror: ' + e.message));
const t0 = Date.now();
await page.goto(url);
await page.waitForFunction(() => document.querySelector('#readout table'), null, { timeout: 240000 });
console.log('ready in', ((Date.now() - t0) / 1000).toFixed(1), 's');
if (process.env.ACTION) await page.evaluate(process.env.ACTION);
await page.waitForTimeout(Number(process.env.WAIT || 3000));
const fps = await page.evaluate(async () => { const f0 = frameCount; await new Promise(r => setTimeout(r, 3000)); return (frameCount - f0) / 3; });
console.log('fps (swiftshader)', fps.toFixed(1));
await page.evaluate(() => { setPaused(true); measure(); });
console.log(await page.evaluate(() => document.querySelector('#readout').innerText));
console.log(await page.evaluate(() => document.querySelector('#palette').innerText));
console.log('particles', await page.evaluate(() => nP), 'vmax', await page.evaluate(() => vmax.toFixed(1)));
await (await page.$('#canvas-container canvas')).screenshot({ path: process.env.OUT || 'shot.png' });
if (process.env.FULL) await page.screenshot({ path: process.env.FULL, fullPage: true });
const width = await page.evaluate(() => [document.documentElement.scrollWidth, window.innerWidth]);
console.log('scrollWidth vs viewport', width);
console.log(logs.filter(l => !l.includes('p5.js says')).slice(0, 20).join('\n'));
await browser.close();
